import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, '..');
const sourceDirectory = path.join(repositoryRoot, 'assets', 'brand');
const destination = path.join(repositoryRoot, 'src', 'brand', 'generated-assets.ts');

const assets = {
  appIcon: 'meknivo-app-icon.svg',
  primaryHorizontal: 'meknivo-primary-horizontal.svg',
  primaryDark: 'meknivo-primary-dark.svg',
  monochromeWhite: 'meknivo-monochrome-white.svg',
  symbol: 'meknivo-symbol.svg',
};

const entries = Object.entries(assets).map(([name, fileName]) => {
  const source = fs.readFileSync(path.join(sourceDirectory, fileName), 'utf8').trim();
  return `  ${name}: ${JSON.stringify(source)},`;
});

const generated = `// Generated by scripts/generate-brand-assets.mjs from assets/brand/*.svg.\n// Run \`npm run brand:generate\` after changing an official brand asset.\nexport const BRAND_SVG = {\n${entries.join('\n')}\n} as const;\n\nexport type BrandAssetName = keyof typeof BRAND_SVG;\n`;

fs.mkdirSync(path.dirname(destination), { recursive: true });
fs.writeFileSync(destination, generated, 'utf8');
console.log(`Generated ${path.relative(repositoryRoot, destination)} from ${Object.keys(assets).length} official SVG assets.`);
